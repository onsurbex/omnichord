inline constexpr bool fmCarrier(int algorithm,int op) {
    if(op<0 || op>5)return false;
    return (fmAlgorithms[static_cast<std::size_t>(std::clamp(algorithm,0,31))][static_cast<std::size_t>(5-op)]&7)==4;
}
inline constexpr int fmCarriers(int algorithm) {
    int result=0;for(int op=0;op<6;++op) if(fmCarrier(algorithm,op)) ++result;return result;
}
